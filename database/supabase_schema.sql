-- Ejecutar en Supabase SQL Editor.
-- Las credenciales viven en Supabase Auth; no se almacenan contrasenas aqui.

create table if not exists public.usuarios (
    id uuid primary key references auth.users(id) on delete cascade,
    cedula varchar(10) not null unique,
    nombre varchar(100) not null,
    apellido varchar(100) not null,
    edad integer not null check (edad between 12 and 100),
    peso numeric(5,2) not null check (peso > 0),
    patologia_o_alergias text,
    alergias_alimentarias text,
    lesiones_actuales text,
    discapacidad_motora text,
    zonas_a_evitar text,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

alter table public.usuarios enable row level security;

drop policy if exists "usuarios_select_own" on public.usuarios;
create policy "usuarios_select_own"
on public.usuarios for select
to authenticated
using (auth.uid() = id);

drop policy if exists "usuarios_insert_own" on public.usuarios;
create policy "usuarios_insert_own"
on public.usuarios for insert
to authenticated
with check (auth.uid() = id);

drop policy if exists "usuarios_update_own" on public.usuarios;
create policy "usuarios_update_own"
on public.usuarios for update
to authenticated
using (auth.uid() = id)
with check (auth.uid() = id);

create index if not exists idx_usuarios_cedula on public.usuarios(cedula);

grant usage on schema public to authenticated;
grant select, insert, update on public.usuarios to authenticated;

alter table public.usuarios add column if not exists alergias_alimentarias text;
alter table public.usuarios add column if not exists lesiones_actuales text;
alter table public.usuarios add column if not exists discapacidad_motora text;
alter table public.usuarios add column if not exists zonas_a_evitar text;

create table if not exists public.aprendizaje_plan_anonimo (
    id bigint generated by default as identity primary key,
    proveedor varchar(30) not null,
    categoria_restriccion varchar(40),
    calificacion integer not null check (calificacion between 1 and 5),
    resultado_seguro boolean not null default false,
    created_at timestamptz not null default now()
);

alter table public.aprendizaje_plan_anonimo enable row level security;
grant insert on public.aprendizaje_plan_anonimo to service_role;

-- 3. Tabla para persistencia del historial de conversaciones del Coach IA
create table if not exists public.coach_mensajes (
    id uuid default gen_random_uuid() primary key,
    user_id uuid references public.usuarios(id) on delete cascade,
    cedula varchar(20),
    role varchar(20) not null check (role in ('user', 'assistant', 'system')),
    content text not null,
    plan jsonb,
    category text,
    rule text,
    suggest_questionnaire boolean default false,
    quick_replies jsonb,
    recommended_intensity varchar(50),
    created_at timestamptz not null default now()
);

create index if not exists idx_coach_mensajes_user_id on public.coach_mensajes(user_id);
create index if not exists idx_coach_mensajes_cedula on public.coach_mensajes(cedula);
create index if not exists idx_coach_mensajes_created_at on public.coach_mensajes(created_at);

alter table public.coach_mensajes enable row level security;
drop policy if exists coach_mensajes_policy on public.coach_mensajes;
create policy coach_mensajes_policy on public.coach_mensajes for all using (true) with check (true);
grant all on public.coach_mensajes to postgres, service_role, anon, authenticated;